# backward sequential algorithm using heart disease dataset UCI





import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, GridSearchCV, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

from mlxtend.feature_selection import SequentialFeatureSelector

from google.colab import files
uploaded = files.upload()

df = pd.read_csv("HeartDiseaseTrain-Test.csv")
df.head()

X = df.drop("target", axis=1)
y = df["target"]

X = pd.get_dummies(X, drop_first=True)

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.2,
    random_state=21,
    stratify=y
)

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

param_grid = {
    'C': np.logspace(-3, 0, 10),   # smaller range reduces model flexibility
    'penalty': ['l2'],
    'solver': ['liblinear'],
    'class_weight': [None],
    'max_iter': [5000]
}

lr = LogisticRegression()

grid = GridSearchCV(
    lr,
    param_grid,
    cv=10,
    scoring='accuracy',
    n_jobs=-1
)

grid.fit(X_train_scaled, y_train)

print("Best Parameters:", grid.best_params_)

best_lr = grid.best_estimator_

sfs = SequentialFeatureSelector(
    best_lr,
    k_features=5,        # limit features (reduces accuracy slightly)
    forward=False,       # Backward Selection
    floating=False,
    scoring='accuracy',
    cv=10,
    n_jobs=-1
)

sfs.fit(X_train_scaled, y_train)

selected_indices = list(sfs.k_feature_idx_)
selected_features = X.columns[selected_indices]

print("Selected Features:")
print(selected_features)

X_train_sel = X_train_scaled[:, selected_indices]
X_test_sel = X_test_scaled[:, selected_indices]

best_lr.fit(X_train_sel, y_train)

y_pred = best_lr.predict(X_test_sel)

accuracy = accuracy_score(y_test, y_pred)

print(f"\nTest Accuracy: {accuracy:.4f}")
print("\nClassification Report:\n")
print(classification_report(y_test, y_pred))

cm = confusion_matrix(y_test, y_pred)

plt.figure(figsize=(6,5))
